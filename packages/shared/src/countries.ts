// Exact match only, never a fuzzy guess; hasOwn so inherited keys like 'constructor' don't match.
export function countryFromName(name: string): CountryCode | null {
  const key = name.trim();
  if (Object.hasOwn(ESPN_COUNTRY_ALIASES, key)) return ESPN_COUNTRY_ALIASES[key] ?? null;
  if (Object.hasOwn(COUNTRY_NAMES, key)) return COUNTRY_NAMES[key] ?? null;
  return null;
}

// Shortest name per code (ties → alphabetical): "Latvia" over "Republic of Latvia".
const DISPLAY_NAMES = new Map<string, string>();
for (const [name, code] of Object.entries(COUNTRY_NAMES)) {
  const best = DISPLAY_NAMES.get(code);
  if (
    best === undefined ||
    name.length < best.length ||
    (name.length === best.length && name < best)
  ) {
    DISPLAY_NAMES.set(code, name);
  }
}

export function countryName(code: CountryCode): string {
  return DISPLAY_NAMES.get(code) ?? code;
}
